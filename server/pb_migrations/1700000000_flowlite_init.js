// Creates the FlowLite sync collections. Every record belongs to one user (owner)
// and is readable and writable only by that user. Deletes are soft (deleted = true).
migrate((app) => {
  const users = app.findCollectionByNameOrId("users");
  users.createRule = null; // no self registration
  app.save(users);

  const owned = "owner = @request.auth.id";
  const rules = {
    listRule: owned,
    viewRule: owned,
    createRule: '@request.auth.id != "" && @request.body.owner = @request.auth.id',
    updateRule: owned + " && (@request.body.owner:isset = false || @request.body.owner = @request.auth.id)",
    deleteRule: null,
  };
  const base = (extra) => [
    // Device generated lowercase UUID, never auto generated by the server.
    { name: "id", type: "text", primaryKey: true, system: true, required: true, min: 36, max: 36, pattern: "^[0-9a-f-]{36}$", autogeneratePattern: "" },
    { name: "owner", type: "relation", required: true, maxSelect: 1, collectionId: users.id, cascadeDelete: true },
    ...extra,
    { name: "updated_at", type: "number", required: true, onlyInt: true },
    { name: "deleted", type: "bool" },
    // Server receive time. Clients use it as the pull cursor.
    { name: "synced_at", type: "autodate", onCreate: true, onUpdate: true },
  ];

  const make = (name, extra, indexes) => {
    app.save(new Collection({ type: "base", name, ...rules, fields: base(extra), indexes }));
  };

  make("transcripts", [
    { name: "text", type: "text", max: 1000000 },
    { name: "raw_text", type: "text", max: 1000000 },
    { name: "device", type: "select", required: true, maxSelect: 1, values: ["android", "linux"] },
    { name: "app_name", type: "text", max: 500 },
    { name: "engine", type: "text", max: 100 },
    { name: "model", type: "text", max: 200 },
    { name: "language", type: "text", max: 20 },
    { name: "duration_ms", type: "number", onlyInt: true },
    { name: "transcribe_ms", type: "number", onlyInt: true },
    { name: "created_at", type: "number", required: true, onlyInt: true },
  ], ["CREATE INDEX idx_transcripts_synced ON transcripts (owner, synced_at)"]);

  make("dictionary", [
    { name: "word", type: "text", required: true, max: 500 },
    { name: "replacement", type: "text", max: 2000 },
  ], ["CREATE INDEX idx_dictionary_synced ON dictionary (owner, synced_at)"]);

  make("settings", [
    { name: "key", type: "text", required: true, max: 200 },
    { name: "value_json", type: "json", maxSize: 100000 },
  ], ["CREATE INDEX idx_settings_synced ON settings (owner, synced_at)"]);
}, (app) => {
  for (const n of ["settings", "dictionary", "transcripts"]) {
    app.delete(app.findCollectionByNameOrId(n));
  }
});
